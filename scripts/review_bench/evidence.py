def gen_dead_code(it: dict) -> list[dict]:
    tree, path, span, decls, inside = excerpt_context(it)
    if not span:
        return []
    lo, hi = span
    fl = tree.lines(path)
    notes: list[str] = []
    refs: list[dict] = []
    lang = lang_of(path)

    # Imported names on the excerpt's lines: uses in the rest of the file.
    for d in inside:
        if d.kind != "import" or lang != "mdk":
            continue
        names = []
        for i in range(max(lo, d.head), min(hi, d.end) + 1):
            ln = strip_comments(fl[i - 1])
            if i == d.head:
                ln = ln.split("{", 1)[1] if "{" in ln else ""
            for a, b in re.findall(r"([A-Za-z_][A-Za-z0-9_']*)(?:\(\.\.\))?(?:\s+as\s+([A-Za-z_][A-Za-z0-9_']*))?", ln):
                if a != "as":
                    names.append(b or a)
        if not names:
            continue
        rest = strip_comments("\n".join(ln for i, ln in enumerate(fl, 1) if not d.start <= i <= d.end), lang)
        unused = [n for n in dict.fromkeys(names) if word_count(rest, n) == 0]
        notes.append(f"Of the {len(names)} name(s) imported on these lines, used nowhere else in the file: "
                     + (", ".join(f"`{u}`" for u in unused) if unused else "none") + ".")

    # Top-level names the excerpt declares: references across the tree. Tests
    # and scripts are counted apart: a helper only a test reaches is still live
    # for that test, so the judge sees both numbers rather than a filtered one.
    tops = [d for d in inside if d.kind in ("sig", "fn", "data", "extern") and d.head >= lo - 3]
    names = [d.name for d in tops]
    if lang == "mdk":
        for d in tops:
            if d.kind == "data":
                names += re.findall(r"(?:=|\|)\s*([A-Z][A-Za-z0-9_']*)", body_code(d))
    names = list(dict.fromkeys(names))[:12]
    if names:
        hits = tree.grep(names, ("-w",), ("*.mdk", "*.sh", "*.mjs", "*.js", "*.c", "Makefile", "*.toml"))
        own = {(d.path, i) for d in tops for i in range(d.start, d.end + 1)}
        usage = []
        for nm in names:
            ext = [(p, n, t) for p, n, t in hits if (p, n) not in own
                   and word_count(t, nm) and not t.lstrip().startswith(("--", "#", "//"))]
            tests = [h for h in ext if h[0].endswith(("_test.mdk", ".sh")) or h[0].startswith("test/")]
            prod = [h for h in ext if h not in tests]
            same = [h for h in prod if h[0] == path]
            other = [h for h in prod if h[0] != path]
            if not ext:
                notes.append(f"`{nm}`: no reference anywhere in the tree outside its own definition.")
            else:
                notes.append(f"`{nm}`: referenced outside its own definition {len(same)} time(s) in this "
                             f"file, {len(other)} in other non-test files, {len(tests)} in tests or scripts.")
            usage += [(nm, h) for h in (same + other + tests)[:4]]
        if usage:
            body = "\n".join(f"{p}:{n}: {t.strip()[:150]}" for _, (p, n, t) in usage[:MAX_LINES])
            refs.append({"file": path, "anchor": "references to " + ", ".join(names[:4]),
                         "sha": tree.sha, "lines": "", "excerpt": body,
                         "note": GEN_NOTE, "fact": "Reference sites of the declared names (comment lines skipped)."})

    # Parameters and local bindings, over every clause of the whole declaration.
    fns = [d for d in inside if d.kind in ("sig", "fn") and lang == "mdk"]
    found = [f for d in fns[:3] for f in local_findings(d)]
    if found:
        notes.append("In the full declaration(s): " + "; ".join(found[:10]) + ".")
    elif fns:
        notes.append("Every parameter and local binding of " + ", ".join(f"`{d.name}`" for d in fns[:3])
                     + " is used in its body.")

    # Whether a branch can be taken depends on what its condition is built from.
    for d in condition_helpers(tree, path, it["excerpt"])[:2]:
        refs.append(make_ref(tree, d.path, d.head, d.end, d.name,
                             f"Definition of `{d.name}`, which a condition in the excerpt depends on.",
                             max_lines=8))
    # The rest of the declaration when the excerpt stops short of its end.
    for d in fns[:1]:
        if d.end > hi:
            refs.append(make_ref(tree, path, hi + 1, d.end, d.name,
                                 f"The rest of `{d.name}` after the excerpt (lines {hi + 1}-{d.end}).",
                                 max_lines=25))
    head = fact_ref(tree, path, "usage search", " ".join(notes)) if notes else None
    return budget(([head] if head else []) + refs)


def condition_helpers(tree: Tree, path: str, excerpt: str) -> list[Decl]:
    """Short top-level definitions (in this file or compiler/support) that the
    excerpt's `if`/`match`/guard conditions reach through its own `let`s."""
    code = interpolations_only(strip_comments(excerpt))
    lets: dict[str, str] = {}
    for m in re.finditer(r"^\s*let\s+([a-z][A-Za-z0-9_']*)\s*=\s*(.*)$", code, re.M):
        lets[m.group(1)] = m.group(2)
    work = []
    for m in re.finditer(r"(?:\bif\b|\bmatch\b|^\s*\|)(.*?)(?:\bthen\b|$)", code, re.M):
        work += re.findall(r"(?<![\w'.])([a-z][A-Za-z0-9_']*)", m.group(1))
    seen: list[str] = []
    while work and len(seen) < 30:
        w = work.pop(0)
        if w in seen or w in KEEP:
            continue
        seen.append(w)
        if w in lets:
            work += re.findall(r"(?<![\w'.])([a-z][A-Za-z0-9_']*)", lets[w])
    out = []
    pools = [path] + sorted(f for f in tree.files() if f.startswith("compiler/support/") and f.endswith(".mdk")
                            and not f.endswith("_test.mdk"))
    for w in seen:
        if w in lets:
            continue
        for f in pools:
            d = next((d for d in tree.decls(f) if d.name == w and d.kind in ("sig", "fn")), None)
            if d and d.end - d.head <= 8:
                out.append(d)
                break
    return out
# Similarity: weighted shingles over raw tokens (copies) and shapes (renamed copies)
# ---------------------------------------------------------------------------
def body_code(d: Decl) -> str:
    """A declaration's code without comments and without its signature lines."""
    lang = lang_of(d.path)
    code = strip_comments(d.text(code_only=True), lang)
    if lang != "mdk":
        return code
    out, in_sig = [], False
    sig_re = re.compile(rf"^(?:public\s+)?(?:export\s+)?(?:extern\s+)?{re.escape(d.name)}\s*:(?!:)")
    for ln in code.split("\n"):
        if sig_re.match(ln):
            in_sig = True
            continue
        if in_sig and ln[:1] in (" ", "\t"):
            continue
        in_sig = False
        if ln.strip() in ("export", "public export"):
            continue
        out.append(ln)
    return "\n".join(out)


def raw_tokens(code: str) -> list[str]:
    return ['"..."' if t[0] == '"' and len(t) > 24 else t for t in TOKEN_RE.findall(code)]


class ShingleIndex:
    """Shingle sets of a pool of declarations, with document frequencies so a
    shingle every declaration has (`v : C v -> C`) weighs nothing."""

    def __init__(self, decls: list[Decl], mode: str, k: int):
        self.mode, self.k = mode, k
        self.sets: dict[int, set] = {}
        df: Counter = Counter()
        for d in decls:
            s = self.of_decl(d)
            self.sets[id(d)] = s
            df.update(s)
        self.df, self.n = df, max(1, len(decls))

    def of_code(self, code: str, names: set[str]) -> set:
        toks = raw_tokens(code) if self.mode == "raw" else shape_tokens(code, names)
        return shingles(toks, self.k)

    def of_decl(self, d: Decl) -> set:
        s = self.sets.get(id(d))
        return s if s is not None else self.of_code(body_code(d), {d.name})

    def idf(self, s) -> float:
        return math.log((self.n + 1) / (self.df.get(s, 0) + 1))

    def weight(self, ss: set) -> float:
        return sum(self.idf(s) for s in ss)

    def sim(self, q: set, c: set) -> tuple[float, float, int]:
        """(score, shared weight, shared count): the mean of weighted cosine and
        weighted containment of the smaller side."""
        inter = q & c
        if len(inter) < 6:
            return 0.0, 0.0, len(inter)
        wi, wq, wc = self.weight(inter), self.weight(q), self.weight(c)
        if wq <= 0 or wc <= 0:
            return 0.0, 0.0, len(inter)
        # Containment alone would let any two-line declaration inside a long
        # excerpt score 1, so it counts in full only for a smaller side of 25+ shingles.
        cont = wi / min(wq, wc) * min(1.0, min(len(q), len(c)) / 25)
        return 0.5 * wi / math.sqrt(wq * wc) + 0.5 * cont, wi, len(inter)


def file_index(tree: Tree, path: str, mode: str, k: int) -> ShingleIndex:
    key = (path, mode, k)
    if key not in tree._idx:
        tree._idx[key] = ShingleIndex([d for d in tree.decls(path) if d.kind not in ("import", "other")], mode, k)
    return tree._idx[key]


