# ---------------------------------------------------------------------------
# Reading the tree at a commit
# ---------------------------------------------------------------------------
def _git(*args: str) -> str:
    r = subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True,
                       errors="replace")
    return r.stdout if r.returncode in (0, 1) else ""


class Tree:
    """One commit's files, greps and parsed declarations, memoized per process."""
    _all: dict[str, "Tree"] = {}

    def __new__(cls, sha: str):
        if sha not in cls._all:
            t = super().__new__(cls)
            t.sha, t._text, t._decls, t._files, t._grep, t._idx = sha, {}, {}, None, {}, {}
            cls._all[sha] = t
        return cls._all[sha]

    def files(self) -> set[str]:
        if self._files is None:
            self._files = set(_git("ls-tree", "-r", "--name-only", self.sha).splitlines())
        return self._files

    def text(self, path: str) -> str | None:
        if path not in self._text:
            self._text[path] = _git("show", f"{self.sha}:{path}") if path in self.files() else None
        return self._text[path]

    def lines(self, path: str) -> list[str]:
        t = self.text(path)
        return t.split("\n") if t else []

    def grep(self, patterns: list[str], flags: tuple[str, ...] = (),
             paths: tuple[str, ...] = ("*.mdk",)) -> list[tuple[str, int, str]]:
        """(path, line, text) for every line matching any pattern at this commit."""
        if not patterns:
            return []
        key = (tuple(patterns), flags, paths)
        if key not in self._grep:
            args = ["grep", "-n", "-I", *flags]
            for p in patterns:
                args += ["-e", p]
            out = _git(*args, self.sha, "--", *paths)
            hits = []
            pre = self.sha + ":"
            for ln in out.splitlines():
                if not ln.startswith(pre):
                    continue
                path, _, rest = ln[len(pre):].partition(":")
                num, _, txt = rest.partition(":")
                if num.isdigit():
                    hits.append((path, int(num), txt))
            self._grep[key] = hits
        return self._grep[key]

    def decls(self, path: str) -> list["Decl"]:
        if path not in self._decls:
            self._decls[path] = parse_decls(self.lines(path), path)
        return self._decls[path]


# ---------------------------------------------------------------------------
# Top-level declarations
# ---------------------------------------------------------------------------
class Decl:
    __slots__ = ("name", "kind", "start", "head", "end", "path", "exported", "lines")

    def __init__(self, name, kind, start, head, end, path, exported, lines):
        # start: first line including leading comments; head: first code line.
        self.name, self.kind, self.start, self.head, self.end = name, kind, start, head, end
        self.path, self.exported, self.lines = path, exported, lines

    def text(self, code_only: bool = False) -> str:
        body = self.lines[(self.head if code_only else self.start) - 1:self.end]
        return "\n".join(body)


MDK_HEAD = re.compile(
    r"^(?:(?P<pub>public\s+)?(?P<exp>export)\s+)?"
    r"(?:(?P<kw>data|type|interface|impl|import|test|prop|extern)\b\s*(?P<rest>.*)"
    r"|(?P<name>[a-z_][A-Za-z0-9_']*)\b(?P<after>.*))$")
SH_HEAD = re.compile(r"^(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*\(\)\s*\{?")
JS_HEAD = re.compile(r"^(?:export\s+)?(?:async\s+)?(?:function\*?\s+(?P<f>[A-Za-z_$][\w$]*)"
                     r"|(?:const|let|var)\s+(?P<v>[A-Za-z_$][\w$]*))")
MK_HEAD = re.compile(r"^(?P<name>[A-Za-z0-9_.%/-]+)\s*(?::(?!=)|[:+?]?=)")


def lang_of(path: str) -> str:
    if path.endswith(".mdk"):
        return "mdk"
    if path.endswith((".mjs", ".js", ".ts")):
        return "js"
    if path.endswith(".sh"):
        return "sh"
    if path.endswith("Makefile") or path.endswith(".mk"):
        return "make"
    if path.endswith(".c") or path.endswith(".h"):
        return "c"
    return "other"


def comment_prefix(lang: str) -> tuple[str, ...]:
    return {"mdk": ("--",), "js": ("//", "/*", "*"), "sh": ("#",), "make": ("#",),
            "c": ("//", "/*", "*")}.get(lang, ("#", "//", "--"))


def parse_decls(lines: list[str], path: str) -> list[Decl]:
    """Column-0 heads start declarations; leading comment runs attach to the next
    head; a signature and its clauses (same name, adjacent) merge into one."""
    lang = lang_of(path)
    cpre = comment_prefix(lang)
    heads: list[tuple[int, int, str, str, bool]] = []  # (lead_start, head, name, kind, exported)
    depth = 0
    lead = None
    pending_export = None
    for i, ln in enumerate(lines, 1):
        s = ln.strip()
        if lang == "mdk":
            opens, closes = ln.count("{-"), ln.count("-}")
            if depth > 0 or ln.startswith("{-"):
                if lead is None:
                    lead = i
                depth = max(0, depth + opens - closes)
                continue
        if not s:
            continue
        if ln[0] in " \t" or ln.startswith(("}", ")", "]")):
            continue
        if ln.startswith(cpre):
            if lead is None:
                lead = i
            continue
        name = kind = None
        exported = False
        if lang == "mdk":
            if s in ("export", "public export"):
                pending_export = pending_export or i
                if lead is None:
                    lead = i
                continue
            m = MDK_HEAD.match(ln)
            if m:
                exported = bool(m.group("exp")) or pending_export is not None
                if m.group("kw"):
                    kind = m.group("kw")
                    rest = m.group("rest")
                    if kind in ("data", "type", "interface"):
                        nm = re.match(r"([A-Z][A-Za-z0-9_']*)", rest)
                        name = nm.group(1) if nm else rest[:40]
                    elif kind == "extern":
                        nm = re.match(r"([a-z_][A-Za-z0-9_']*)", rest)
                        name = nm.group(1) if nm else rest[:40]
                    elif kind == "import":
                        name = rest.split("{")[0].split(" as ")[0].strip() or rest[:40]
                    else:
                        name = rest[:60]
                else:
                    name = m.group("name")
                    kind = "sig" if re.match(r"\s*:(?!:)", m.group("after")) else "fn"
        elif lang == "sh":
            m = SH_HEAD.match(ln)
            if m:
                name, kind = m.group("name"), "fn"
        elif lang == "js":
            m = JS_HEAD.match(ln)
            if m:
                name, kind = m.group("f") or m.group("v"), "fn"
        elif lang == "make":
            m = MK_HEAD.match(ln)
            if m:
                name, kind = m.group("name"), "fn"
        if name is None:
            name, kind = s[:40], "other"
        start = min(x for x in (lead, pending_export, i) if x is not None)
        heads.append((start, i, name, kind, exported))
        lead = None
        pending_export = None
    decls: list[Decl] = []
    for n, (start, head, name, kind, exported) in enumerate(heads):
        nxt = heads[n + 1][0] if n + 1 < len(heads) else len(lines) + 1
        end = nxt - 1
        while end > head and not lines[end - 1].strip():
            end -= 1
        prev = decls[-1] if decls else None
        if (prev and prev.name == name and prev.kind in ("sig", "fn") and kind in ("sig", "fn")
                and lang == "mdk"):
            prev.end = end
            prev.exported = prev.exported or exported
            continue
        decls.append(Decl(name, kind, start, head, end, path, exported, lines))
    return decls


def decl_sig(d: Decl) -> str:
    """The signature text, joined across continuation lines."""
    ls = d.lines
    for i in range(d.head - 1, d.end):
        m = re.match(rf"^(?:public\s+)?(?:export\s+)?(?:extern\s+)?\s*{re.escape(d.name)}\s*:(?!:)(.*)", ls[i])
        if m:
            parts = [m.group(1).strip()]
            j = i + 1
            while j < d.end and ls[j].startswith((" ", "\t")) and parts[-1].endswith(("->", "=>", ",", "(")):
                parts.append(ls[j].strip())
                j += 1
            return " ".join(parts)
    return ""


def interface_methods(lines: list[str], path: str) -> list[Decl]:
    """Methods declared inside `interface ... where` blocks, as pseudo-declarations:
    the stdlib index lists no interface methods, and they are what a hand-rolled
    `orElse` or `compare` duplicates."""
    out = []
    i = 0
    n = len(lines)
    while i < n:
        if re.match(r"^(?:export\s+)?interface\b", lines[i]):
            j = i + 1
            while j < n and (not lines[j].strip() or lines[j].startswith((" ", "\t"))):
                m = re.match(r"^  ([a-z_][A-Za-z0-9_']*)\s*:(?!:)", lines[j])
                if m:
                    k = j + 1
                    while k < n and lines[k].startswith("    "):
                        k += 1
                    # the method's default clauses, if any, follow later in the block
                    out.append(Decl(m.group(1), "method", i + 1, j + 1, k, path, True, lines))
                j += 1
            i = j
        else:
            i += 1
    return out


def locate(tree: Tree, it: dict) -> tuple[int, int] | None:
    """The excerpt's line range in its file at its commit (1-based, inclusive)."""
    fl = tree.lines(it["file"])
    ex = it["excerpt"].split("\n")
    if not fl or not ex:
        return None
    first = ex[0]
    for i, ln in enumerate(fl):
        if ln == first and fl[i:i + len(ex)] == ex:
            return i + 1, i + len(ex)
    m = re.match(r"^(\d+)-(\d+)$", str(it.get("lines") or ""))
    if m:
        return int(m.group(1)), int(m.group(2))
    return None


def overlapping(decls: list[Decl], lo: int, hi: int) -> list[Decl]:
    return [d for d in decls if d.start <= hi and d.end >= lo]


