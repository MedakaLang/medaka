def _range(s: str) -> tuple[int, int] | None:
    m = re.match(r"^(\d+)-(\d+)$", str(s or ""))
    return (int(m.group(1)), int(m.group(2))) if m else None


def covers(gen_refs: list[dict], cur: dict) -> bool:
    """A generated ref covers a curated one when it names the same file and the
    same declaration (or overlapping lines); a curated whole-module ref is
    covered by any generated ref into that file."""
    cf = cur.get("file") or ""
    ca = (cur.get("anchor") or "").strip()
    cr = _range(cur.get("lines"))
    if cur.get("fact") and not cur.get("excerpt"):
        # A curated finding with no code: covered when a generated fact names the
        # same thing (one of its names, or its path).
        keys = [n for n in re.split(r"[ ,/]+", ca) if re.fullmatch(r"[A-Za-z_][\w']*", n)] + [cf]
        if any(f"`{k}`" in (g.get("fact") or "") for g in gen_refs for k in keys if k):
            return True
    for g in gen_refs:
        if g.get("file") != cf and not (g.get("excerpt") and f"{cf}:" in g["excerpt"]):
            continue
        if g.get("file") != cf:
            # a reference listing (`path:line: text`) that names the curated file
            lines = [int(x) for x in re.findall(rf"^{re.escape(cf)}:(\d+):", g["excerpt"], re.M)]
            if not ca or (cr and any(cr[0] <= x <= cr[1] for x in lines)):
                return True
            continue
        if not ca:
            return True
        ga = g.get("anchor") or ""
        names = [n for n in re.split(r"[ ,/]+", ca) if n]
        if ca == ga or any(n in re.split(r"[ ,/]+", ga) for n in names):
            return True
        gr = _range(g.get("lines"))
        if cr and gr and gr[0] <= cr[1] and gr[1] >= cr[0]:
            return True
        if any(re.search(rf"`{re.escape(n)}`", g.get("fact") or "") for n in names):
            return True
    return False


def resolvable(cur: dict) -> bool:
    note = (cur.get("note") or "").lower()
    if "not found" in note:
        return False
    f = cur.get("file") or ""
    return bool(f) and not f.startswith(".claude/") and not f.endswith(".md")
