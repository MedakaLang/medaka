"""Stage-1 evidence generation: the code a judge needs that lies outside the
excerpt, found mechanically.

A generator sees only what a review pipeline would have for a diff unit: the
item's `file`, `sha`, `excerpt` and its line range. It never reads what a
labeller wrote (`summary`, `notes`, `evidence_refs`, `fix`, `polarity`,
`evidence_scope`), and it does not read `anchor` either, which is sometimes a
labeller's prose; declarations are found from the excerpt's own position in
the file. Everything is read at the item's commit with `git show` and
`git grep`, so a generated ref describes the tree the excerpt was cut from.

Each generator returns refs in the fixture shape `{file, anchor, sha, lines,
excerpt, note, fact}`. `fact` is a neutral, mechanically checkable statement of
what a search found, including absence ("no
reference outside its own definition"), which is evidence in itself. Output is
capped: MAX_REFS refs, MAX_LINES lines per excerpt, MAX_CHARS characters over
all excerpts and notes of one item.

Generated refs are cached under `.cache/evidence/` by a hash of this file's
source and the item's code fields, so an edit here regenerates everything.
"""
