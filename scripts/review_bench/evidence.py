def gen_magic_literal(it: dict) -> list[dict]:
    tree, path, span, decls, inside = excerpt_context(it)
    code = strip_comments(it["excerpt"], lang_of(path))
    lits = []
    for x in re.findall(r"(?<![\w.])(\d{2,})(?![\w.])", code):
        if x not in lits and x not in ("10", "16", "32", "64", "100"):
            lits.append(x)
    for x in re.findall(r"(?<![\w.])(\d{2,})(?=-byte|\b)", "\n".join(re.findall(r'"[^"]*"', code))):
        if x not in lits:
            lits.append(x)
    if not lits:
        return []
    pats = [rf"^ *[a-z][A-Za-z0-9_']* *= *{x} *$" for x in lits[:8]]
    hits = tree.grep(pats, ("-E",), ("*.mdk",))
    near = [h for h in hits if h[0] == path] + [h for h in hits if h[0].startswith("stdlib/") and h[0] != path]
    refs, seen = [], set()
    found = set()
    for p, ln, t in near:
        d = next((d for d in tree.decls(p) if d.head <= ln <= d.end), None)
        if not d or (p, d.name) in seen:
            continue
        seen.add((p, d.name))
        lit = re.search(r"=\s*(\d+)", t).group(1)
        found.add(lit)
        refs.append(make_ref(tree, p, d.start, d.end, d.name,
                             f"A named constant with the value {lit}.", max_lines=8))
        if len(refs) >= MAX_REFS - 1:
            break
    missing = [x for x in lits[:8] if x not in found]
    fact = ("Numeric literals in the excerpt: " + ", ".join(lits[:8]) + ". "
            + ("Named constants with these values: " + ", ".join(sorted(found)) + ". " if found else "")
            + ("No constant in this file or the stdlib is defined as " + ", ".join(missing) + "." if missing else ""))
    return budget([fact_ref(tree, path, "literal search", fact)] + refs)


