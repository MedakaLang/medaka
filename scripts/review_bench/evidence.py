TOKEN_RE = re.compile(r'"(?:\\.|[^"\\])*"|\d+|[A-Za-z_][A-Za-z0-9_\']*|::|->|=>|\|>|\+\+|&&|\|\||==|/=|<=|>=|\S')
KEEP = {"if", "then", "else", "match", "let", "in", "do", "where", "case", "of", "True", "False",
        "None", "Some", "Ok", "Err", "Unit", "not", "return", "function", "const", "for", "while",
        "fi", "done", "local", "echo", "printf"}
STOP_TOKENS = {"the", "a", "an", "of", "to", "and", "is", "in", "on", "for", "with", "by", "as",
               "it", "its", "be", "at", "from", "that", "this", "when", "not", "no", "every",
               "one", "if", "then", "let", "match", "go", "loop", "int", "str", "s", "x", "xs", "n",
               "i", "k", "v", "e", "f", "p"}


def strip_comments(text: str, lang: str = "mdk") -> str:
    out = []
    depth = 0
    for ln in text.split("\n"):
        if lang == "mdk":
            if depth or ln.lstrip().startswith("{-"):
                depth = max(0, depth + ln.count("{-") - ln.count("-}"))
                continue
            s = ln.lstrip()
            if s.startswith("--"):
                continue
            ln = re.sub(r"\s--\s.*$", "", ln)
        else:
            s = ln.lstrip()
            if s.startswith(comment_prefix(lang)):
                continue
        out.append(ln)
    return "\n".join(out)


def shape_tokens(code: str, self_names: set[str] = frozenset()) -> list[str]:
    toks = []
    for t in TOKEN_RE.findall(code):
        if t[0] == '"':
            toks.append('"' if len(t) > 4 else t)
        elif t[0].isdigit():
            toks.append(t if t in ("0", "1", "2") else "N")
        elif t[0].isalpha() or t[0] == "_":
            if t in self_names:
                toks.append("SELF")
            elif t in KEEP:
                toks.append(t)
            elif t[0].isupper():
                toks.append("C")
            else:
                toks.append("v")
        else:
            toks.append(t)
    return toks


def shingles(toks: list[str], k: int) -> set[tuple]:
    if len(toks) <= k:
        return {tuple(toks)} if toks else set()
    return {tuple(toks[i:i + k]) for i in range(len(toks) - k + 1)}


def norm_line(ln: str) -> str:
    return " ".join(ln.split())


def distinctive_lines(code: str, lang: str, n: int = 6, min_len: int = 24) -> list[str]:
    """The longest code lines worth grepping for verbatim elsewhere."""
    seen, out = set(), []
    for ln in strip_comments(code, lang).split("\n"):
        s = norm_line(ln)
        if len(s) < min_len or s in seen:
            continue
        if re.fullmatch(r"[\W_]*", s) or s.startswith(("import ", "export", "|")):
            continue
        seen.add(s)
        out.append(s)
    out.sort(key=len, reverse=True)
    return out[:n]


def camel_tokens(name: str) -> list[str]:
    parts = re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z]+|\d+", name)
    return [p.lower() for p in parts if p]


# ---------------------------------------------------------------------------
# Types: a one-way signature matcher (candidate variables bind to excerpt types)
# ---------------------------------------------------------------------------
def _strip_type(sig: str) -> str:
    sig = re.sub(r"<[^<>]*>", " ", sig)          # effect rows
    if "=>" in sig:
        sig = sig.split("=>")[-1]                # constraints
    return sig.strip()


def parse_type(sig: str):
    toks = re.findall(r"->|[A-Za-z_][A-Za-z0-9_']*|[(),\[\]{}]", _strip_type(sig))
    pos = [0]

    def peek():
        return toks[pos[0]] if pos[0] < len(toks) else None

    def take():
        pos[0] += 1
        return toks[pos[0] - 1]

    def arrow():
        parts = [app()]
        while peek() == "->":
            take()
            parts.append(app())
        return parts[0] if len(parts) == 1 else ("fn", tuple(parts))

    def app():
        head = atom()
        args = []
        while peek() not in (None, "->", ")", ",", "]", "}"):
            args.append(atom())
        if not args:
            return head
        return ("app", head, tuple(args))

    def atom():
        t = peek()
        if t is None:
            return ("con", "?")
        take()
        if t == "(":
            if peek() == ")":
                take()
                return ("con", "Unit")
            items = [arrow()]
            while peek() == ",":
                take()
                items.append(arrow())
            if peek() == ")":
                take()
            return items[0] if len(items) == 1 else ("tup", tuple(items))
        if t in ("[", "{"):
            depth = 1
            while peek() is not None and depth:
                x = take()
                depth += x in ("[", "{")
                depth -= x in ("]", "}")
            return ("con", "Rec")
        return ("var", t) if t[0].islower() else ("con", t)

    try:
        return arrow() if toks else None
    except (IndexError, RecursionError):
        return None


def _match(c, q, sub: dict) -> bool:
    if c is None or q is None:
        return False
    if c[0] == "var":
        if c[1] in sub:
            return sub[c[1]] == q
        sub[c[1]] = q
        return True
    if c[0] != q[0]:
        return False
    if c[0] == "con":
        return c[1] == q[1]
    if c[0] == "app":
        return (len(c[2]) == len(q[2]) and _match(c[1], q[1], sub)
                and all(_match(x, y, sub) for x, y in zip(c[2], q[2])))
    if c[0] in ("fn", "tup"):
        return len(c[1]) == len(q[1]) and all(_match(x, y, sub) for x, y in zip(c[1], q[1]))
    return False


def _nodes(t) -> tuple[int, int]:
    """(all nodes, concrete constructor nodes)."""
    if t is None:
        return 0, 0
    if t[0] == "var":
        return 1, 0
    if t[0] == "con":
        return 1, 1
    if t[0] == "app":
        subs = [t[1], *t[2]]
    else:
        subs = list(t[1])
    a, c = 1, 0
    for s in subs:
        x, y = _nodes(s)
        a, c = a + x, c + y
    return a, c


def sig_score(cand_sig: str, query_sig: str) -> float:
    """1.0 down to 0.5 for a match (more for a more specific candidate), a little
    less when only an argument permutation matches, 0 otherwise."""
    c, q = parse_type(cand_sig), parse_type(query_sig)
    if c is None or q is None:
        return 0.0
    allnodes, concrete = _nodes(c)
    spec = 0.5 + 0.5 * (concrete / allnodes if allnodes else 0)
    if _match(c, q, {}):
        return spec
    if c[0] == "fn" and q[0] == "fn" and len(c[1]) == len(q[1]) and 3 <= len(c[1]) <= 4:
        args_q, res_q = q[1][:-1], q[1][-1]
        from itertools import permutations
        for perm in permutations(args_q):
            if _match(c, ("fn", tuple(perm) + (res_q,)), {}):
                return 0.85 * spec
    return 0.0


