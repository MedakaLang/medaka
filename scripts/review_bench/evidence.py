MAX_REFS = 3
GEN_NOTE = "generated by scripts/review_bench/evidence.py"
MAX_LINES = 40
MAX_CHARS = 6000
MAX_STATUS = 12  # findings listed in a comment.stale fact, absences first

# Classes with a generator. Every other class gets no generated evidence.
