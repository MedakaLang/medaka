# Rendering a ref
# ---------------------------------------------------------------------------
def make_ref(tree: Tree, path: str, lo: int, hi: int, anchor: str, fact: str,
             max_lines: int = MAX_LINES) -> dict:
    ls = tree.lines(path)
    hi = min(hi, len(ls), lo + max_lines - 1)
    ex = "\n".join(ls[lo - 1:hi]) if ls and lo >= 1 else ""
    return {"file": path, "anchor": anchor, "sha": tree.sha, "lines": f"{lo}-{hi}" if ex else "",
            "excerpt": ex, "note": GEN_NOTE, "fact": fact}


def fact_ref(tree: Tree, path: str, anchor: str, fact: str) -> dict:
    """A location-only ref whose content is the fact."""
    return {"file": path, "anchor": anchor, "sha": tree.sha, "lines": "", "excerpt": "", "note": GEN_NOTE,
            "fact": fact}


def budget(refs: list[dict]) -> list[dict]:
    out, used = [], 0
    for r in refs[:MAX_REFS]:
        size = len(r["excerpt"]) + len(r["fact"])
        if used + size > MAX_CHARS:
            room = MAX_CHARS - used - len(r["fact"])
            if room < 200:
                break
            kept = []
            for ln in r["excerpt"].split("\n"):
                if sum(len(k) + 1 for k in kept) + len(ln) > room:
                    break
                kept.append(ln)
            r = dict(r, excerpt="\n".join(kept))
            lo = r["lines"].split("-")[0] if r["lines"] else ""
            if lo:
                r["lines"] = f"{lo}-{int(lo) + len(kept) - 1}"
            size = len(r["excerpt"]) + len(r["fact"])
        out.append(r)
        used += size
    return out


def _short(ls: list[str], n: int) -> str:
    return ", ".join(ls[:n]) + (f" and {len(ls) - n} more" if len(ls) > n else "")


# ---------------------------------------------------------------------------
# What the excerpt declares
# ---------------------------------------------------------------------------
def excerpt_context(it: dict):
    tree = Tree(it["sha"])
    path = it["file"]
    span = locate(tree, it)
    decls = tree.decls(path) if tree.text(path) is not None else []
    inside = overlapping(decls, *span) if span else []
    return tree, path, span, decls, inside


def split_top(s: str, seps: str = "=|") -> tuple[int, str] | None:
    """The first `=` (not part of `==`, `=>`, `/=`, `<=`, `>=`) or ` | ` outside
    brackets in `s`: where a clause head ends. (index, which)."""
    depth = 0
    i = 0
    while i < len(s):
        ch = s[i]
        if ch == '"':
            j = i + 1
            while j < len(s) and s[j] != '"':
                j += 2 if s[j] == "\\" else 1
            i = j + 1
            continue
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif depth == 0 and ch == "=" and "=" in seps:
            prev = s[i - 1] if i else ""
            nxt = s[i + 1] if i + 1 < len(s) else ""
            if prev not in "=<>/!:" and nxt not in "=>":
                return i, "="
        elif depth == 0 and ch == "|" and "|" in seps:
            prev = s[i - 1] if i else ""
            nxt = s[i + 1] if i + 1 < len(s) else ""
            if prev in " \t" and nxt in " \t" and "|" not in (prev, nxt):
                return i, "|"
        i += 1
    return None


def pattern_binders(head: str) -> list[str]:
    """Variables a clause head or `let` pattern binds (record field labels and
    constructors excluded)."""
    h = re.sub(r"\b[a-z][A-Za-z0-9_']*\s*=(?![=>])", " ", head)   # `{ field = var }` labels
    h = re.sub(r'"(?:\\.|[^"\\])*"', " ", h)
    names = re.findall(r"(?<![\w.'])([a-z][A-Za-z0-9_']*)(?![\w'])", h)
    return [n for n in dict.fromkeys(names) if n not in KEEP and n != "as"]


STRING_RE = re.compile(r'"(?:\\.|[^"\\])*"')


def interpolations_only(code: str) -> str:
    """`code` with each string literal reduced to its `\\{...}` interpolations, so
    a word inside a message does not count as a use of a variable."""
    return STRING_RE.sub(lambda m: " ".join(re.findall(r"\\\{([^}]*)\}", m.group(0))) or '""', code)


def clauses(d: Decl) -> list[tuple[int, str, str]]:
    """(clause number, head text after the name, body text) per clause."""
    out: list[list] = []
    for ln in interpolations_only(body_code(d)).split("\n"):
        m = re.match(rf"^{re.escape(d.name)}(?![\w'])(.*)$", ln)
        if m:
            rest = m.group(1)
            cut = split_top(rest)
            head, body = (rest[:cut[0]], rest[cut[0] + (1 if cut[1] == "=" else 0):]) if cut else (rest, "")
            out.append([len(out) + 1, head, [body]])
        elif out:
            out[-1][2].append(ln)
    return [(n, h, "\n".join(b)) for n, h, b in out]


def word_count(text: str, name: str) -> int:
    return len(re.findall(rf"(?<![\w'.]){re.escape(name)}(?![\w'])", text))


def self_call_only(body: str, fname: str, var: str) -> bool:
    """Every occurrence of `var` in `body` sits after a call of `fname` on its line."""
    seen = False
    for ln in body.split("\n"):
        if not word_count(ln, var):
            continue
        seen = True
        call = re.search(rf"(?<![\w']){re.escape(fname)}(?![\w'])", ln)
        if not call:
            return False
        first = re.search(rf"(?<![\w'.]){re.escape(var)}(?![\w'])", ln)
        if first.start() < call.start():
            return False
    return seen


def local_findings(d: Decl) -> list[str]:
    out = []
    cls = clauses(d)
    multi = len(cls) > 1
    for n, head, body in cls:
        where = f"`{d.name}`" + (f" (clause {n})" if multi else "")
        for p in pattern_binders(head):
            if p.startswith("_"):
                continue
            if word_count(body, p) == 0:
                out.append(f"parameter `{p}` of {where} is never used in its body")
            elif self_call_only(body, d.name, p):
                out.append(f"parameter `{p}` of {where} is only passed back into `{d.name}`")
        blines = body.split("\n")
        for i, ln in enumerate(blines):
            m = re.match(r"^\s*let\s+(.+?)\s*=(?![=>])", ln) or re.match(r"^\s+(\w[\w']*)\s*<-", ln)
            if not m:
                continue
            pat = m.group(1)
            if ":" in pat and not pat.startswith("("):
                pat = pat.split(":")[0]
            later = "\n".join(blines[i + 1:]) + "\n" + ln[m.end():]
            for v in pattern_binders(pat):
                if v.startswith("_") or v == d.name:
                    continue
                if word_count(later, v) == 0:
                    out.append(f"local `{v}` in {where} is bound and never used")
    return out


