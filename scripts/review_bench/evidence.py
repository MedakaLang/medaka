def code_decls(tree: Tree, path: str) -> list[Decl]:
    return [d for d in tree.decls(path) if d.kind in ("sig", "fn")]


def library_pool(tree: Tree) -> list[Decl]:
    """Every stdlib and compiler/support declaration at the commit, interface
    methods and externs included."""
    key = ("_libpool",)
    if key in tree._idx:
        return tree._idx[key]
    pool = []
    for f in sorted(tree.files()):
        if not f.endswith(".mdk") or f.endswith("_test.mdk"):
            continue
        if f.startswith("stdlib/") or f.startswith("compiler/support/"):
            pool += [d for d in tree.decls(f) if d.kind in ("sig", "fn", "extern")]
            if f.startswith("stdlib/"):
                pool += interface_methods(tree.lines(f), f)
    tree._idx[key] = pool
    return pool


def doc_words(d: Decl) -> list[str]:
    lead = "\n".join(d.lines[d.start - 1:d.head - 1])
    words = re.findall(r"[A-Za-z][a-z]+", lead)
    return [w.lower() for w in words if w.lower() not in STOP_TOKENS][:40]


def name_vec(d: Decl, with_doc: bool) -> Counter:
    v = Counter(t for t in camel_tokens(d.name) if t not in STOP_TOKENS)
    if with_doc:
        v.update(doc_words(d))
    return v


# Hand-rolled recursions over a list, Option or Result that a Prelude-style
# combinator expresses (the rubric names map/filter/any/all/find/count/elem).
# Each pattern runs on the body with the declaration's own name replaced by
# SELF; the names are looked up in the library pool at the item's commit.
CATALOGUE: list[tuple[tuple[str, ...], tuple[str, ...]]] = [
    ((r"\[\]\s*=\s*False", r"\|\|\s*SELF\b"), ("any", "elem", "anyList", "contains")),
    ((r"\[\]\s*=\s*True", r"&&\s*SELF\b"), ("all", "allList")),
    ((r"\[\]\s*=\s*\[\]", r"=\s*[^|\n]*::\s*SELF\b"), ("map", "filterMap", "flatMap")),
    ((r"\[\]\s*=\s*\[\]", r"(?:\|[^\n]*=|then)\s*\w+\s*::\s*SELF\b"), ("filter", "filterList", "partition")),
    ((r"\[\]\s*=\s*None", r"Some\b", r"SELF\b"), ("find", "lookup", "elemIndex")),
    ((r"\[\]\s*=\s*0\b", r"\+\s*SELF\b"), ("count", "sum", "length")),
    ((r"\[\]\s*=\s*\(\)", r"let\s+_\s*=", r"SELF\b"), ("each", "traverse_", "forEach")),
    ((r"SELF\s+\[\]\s+\w+\s*=\s*\w+\s*$|\[\]\s+(\w+)\s*=\s*\1\s*$", r"SELF\s+\w+\s+\("), ("foldl", "fold", "fromList")),
    ((r"Some\s+(\w+)\s*=>\s*\1\s*$", r"None\s*=>"), ("optionOr", "withDefault", "orElse")),
    ((r"Ok\s+(\w+)\s*=>\s*Ok\s+\1\b", r"Err\s+\w+\s*=>\s*Err\s*\("), ("mapErr",)),
    ((r"Err\s+(\w+)\s*=>\s*Err\s+\1\b", r"Ok\s+\w+\s*=>"), ("andThen", "map", "mapErr")),
    ((r"Some\s+\w+\s*=>\s*Some\s*\(", r"None\s*=>\s*None"), ("map", "andThen")),
    ((r"None\s*=>\s*None", r"Some\s+\w+\s*=>"), ("andThen", "map")),
    # the same Option shapes written as clauses instead of a match
    ((r"SELF\s+\w+\s+\(Some\s+(\w+)\)\s*=\s*\1\s*$", r"SELF\s+\w+\s+None\s*="), ("optionOr", "withDefault")),
    ((r"SELF\s+\(Some\s+\w+\)\s+_\s*=\s*Some\b", r"SELF\s+None\s+(\w+)\s*=\s*\1\s*$"), ("orElse",)),
    ((r"SELF\s+(?:\w+\s+)?\(Some\s+\w+\)\s*=\s*Some\b", r"SELF\s+(?:\w+\s+)?None\s*=\s*None"), ("map", "andThen")),
    ((r"SELF\s+(?:\w+\s+)?\(Some\s+\w+\)\s*=", r"SELF\s+(?:\w+\s+)?None\s*=\s*None"), ("andThen", "map")),
    ((r"join\s+\"\"\s*\(\s*map", r"\\n"), ("unlines", "joinNl", "join")),
]


def catalogue_hits(code: str, name: str) -> list[str]:
    body = re.sub(rf"(?<![\w']){re.escape(name)}(?![\w'])", "SELF", code)
    out: list[str] = []
    for pats, names in CATALOGUE:
        if all(re.search(p, body, re.M) for p in pats):
            out += [n for n in names if n not in out]
    return out


def gen_dup_existing(it: dict) -> list[dict]:
    tree, path, span, decls, inside = excerpt_context(it)
    fns = [d for d in inside if d.kind in ("sig", "fn")]
    if not fns:
        return []
    pool = library_pool(tree)
    lib = [d for d in pool if d.path != path]
    same_file = [d for d in code_decls(tree, path) if d not in fns]
    key = ("_libshape",)
    if key not in tree._idx:
        tree._idx[key] = ShingleIndex(lib, "shape", 4)
    lib_idx = tree._idx[key]
    file_idx = file_index(tree, path, "shape", 4)
    df: Counter = Counter()
    vecs = {}
    for d in lib + same_file:
        v = name_vec(d, True)
        vecs[id(d)] = v
        df.update(set(v))
    N = max(1, len(vecs))

    def idf(t):
        return math.log((N + 1) / (df.get(t, 0) + 1))

    by_name: dict[str, list[Decl]] = {}
    for d in lib:
        by_name.setdefault(d.name, []).append(d)
    picked: dict[tuple, tuple[float, Decl, str]] = {}

    def offer(score, d, why):
        k = (d.path, d.name)
        if k not in picked or picked[k][0] < score:
            picked[k] = (score, d, why)

    for q in fns[:4]:
        qbody = body_code(q)
        for rank, nm in enumerate(catalogue_hits(qbody, q.name)):
            for d in sorted(by_name.get(nm, []), key=lambda d: (not d.path.startswith("stdlib/core"),
                                                                 not d.path.startswith("stdlib/"), d.path))[:1]:
                offer(2.0 - 0.05 * rank, d, f"for `{q.name}`: body has the shape of `{nm}`")
        qsig = decl_sig(q)
        qsh_lib = lib_idx.of_code(qbody, {q.name})
        qv = name_vec(q, False)
        called = [w for w in re.findall(r"(?<![\w'])[a-z][A-Za-z0-9]*", interpolations_only(qbody)) if w not in KEEP]
        qv.update(t for t in camel_tokens(" ".join(called)) if t not in STOP_TOKENS)
        qlow = q.name.lower()
        qnorm = math.sqrt(sum((idf(t) * c) ** 2 for t, c in qv.items())) or 1.0
        for d in lib + same_file:
            csig = decl_sig(d)
            ss = sig_score(csig, qsig) if csig and qsig else 0.0
            idx = file_idx if d.path == path else lib_idx
            bs = 0.0 if d.kind in ("extern", "method") else idx.sim(qsh_lib, idx.of_decl(d))[0]
            cv = vecs[id(d)]
            dot = sum(idf(t) ** 2 * c * cv[t] for t, c in qv.items() if t in cv)
            cnorm = math.sqrt(sum((idf(t) * c) ** 2 for t, c in cv.items())) or 1.0
            ns = dot / (qnorm * cnorm)
            # A renamed twin keeps the original's name inside its own (`orElseOpt`).
            twin = len(d.name) >= 4 and d.name.lower() in qlow and d.name != q.name
            score = 0.45 * min(1.0, bs) + 0.35 * ss + 0.35 * ns + (0.3 if twin else 0.0)
            if d.path == path:
                score *= 0.8
            if score <= 0.15:
                continue
            why = [w for w, on in (("the excerpt's name contains its name", twin), ("signature fits", ss > 0),
                                   ("similar body shape", bs >= 0.3),
                                   ("shares name or doc words", ns >= 0.2)) if on]
            offer(score, d, f"for `{q.name}`: " + ", ".join(why or ["weak match"]))
    best = sorted(picked.values(), key=lambda x: -x[0])[:MAX_REFS]
    refs = []
    for score, d, why in best:
        where = "this file" if d.path == path else d.path
        lo = d.start if d.head - d.start <= 6 else d.head - 3
        refs.append(make_ref(tree, d.path, lo, d.end, d.name,
                             f"`{d.name}` in {where}, {why}.",
                             max_lines=18))
    return budget(refs)


IDENT_TOKEN = re.compile(r"[a-z_][A-Za-z0-9_']*")


def line_pattern(line: str) -> str | None:
    """An extended regex matching `line` with every lower-case identifier
    generalized, or None when too little of the line is left to anchor on."""
    toks = TOKEN_RE.findall(line)
    anchors = sum(1 for t in toks if not (IDENT_TOKEN.fullmatch(t) and t not in KEEP))
    if len(toks) < 6 or anchors < 3:
        return None
    parts = []
    for t in toks:
        if IDENT_TOKEN.fullmatch(t) and t not in KEEP:
            parts.append("[A-Za-z_][A-Za-z0-9_']*")
        else:
            parts.append(re.sub(r"([\\.^$|?*+()\[\]{}])", r"\\\1", t))
    return " *".join(parts)


def similar_decls(tree: Tree, path: str, qdecls: list[Decl], qcode: str, *, cross: bool,
                  same: bool, exclude: tuple[int, int] | None) -> list[tuple[float, Decl, str]]:
    """Declarations whose code resembles `qcode`, in the same file and/or elsewhere.
    Cross-file candidates come from greps at the commit: the same name, verbatim
    and identifier-generalized distinctive lines, and declaration names sharing a
    long name word. Scoring uses the home file's shingle frequencies."""
    lang = lang_of(path)
    qnames = {d.name for d in qdecls}
    qbody = strip_comments(qcode, lang)
    raw_idx = file_index(tree, path, "raw", 4)
    shp_idx = file_index(tree, path, "shape", 5)
    qraw = raw_idx.of_code(qbody, qnames)
    qshp = shp_idx.of_code(qbody, qnames)
    qlines = {norm_line(ln) for ln in qbody.split("\n") if len(norm_line(ln)) >= 16}
    cands: dict[tuple, Decl] = {}

    def overl(d):
        return exclude and d.start <= exclude[1] and d.end >= exclude[0]
    if same:
        for d in tree.decls(path):
            if d.kind not in ("import", "other") and not overl(d):
                cands[(d.path, d.start)] = d
    if cross:
        ext = "*" + Path(path).suffix if Path(path).suffix else "*"
        paths = ("*.mdk",) if lang == "mdk" else (ext,)
        hits = []
        names = sorted(n for n in qnames if len(n) >= 3 and re.fullmatch(r"[A-Za-z_][\w']*", n))
        if names:
            pat = r"^(export +)?(" + "|".join(re.escape(n) for n in names) + r")\b"
            hits += tree.grep([pat], ("-E",), paths)
        dl = distinctive_lines(qcode, lang)
        if dl:
            hits += tree.grep(dl, ("-F",), paths)[:200]
            gen = [p for p in (line_pattern(x) for x in dl[:4]) if p]
            if gen:
                hits += tree.grep(gen, ("-E",), paths)[:200]
        words = [w for n in qnames for w in camel_tokens(n) if len(w) >= 5 and w not in STOP_TOKENS]
        for w in list(dict.fromkeys(words))[:3]:
            cap = w[0].upper() + w[1:]
            hits += tree.grep([rf"^(export +)?[a-z][A-Za-z0-9_']*{cap}[A-Za-z0-9_']* *:",
                               rf"^(export +)?{w}[A-Za-z0-9_']* *:"], ("-E",), paths)[:40]
        byfile: dict[str, list[int]] = {}
        for p, n, _ in hits:
            if p != path:
                byfile.setdefault(p, []).append(n)
        for p, ns in list(byfile.items())[:60]:
            ds = tree.decls(p)
            for n in sorted(set(ns))[:20]:
                for d in ds:
                    if d.start <= n <= d.end and d.kind not in ("import",):
                        cands[(d.path, d.start)] = d
    out = []
    for d in cands.values():
        dbody = body_code(d)
        rs = raw_idx.sim(qraw, raw_idx.of_code(dbody, {d.name}))[0]
        ss = shp_idx.sim(qshp, shp_idx.of_code(dbody, {d.name}))[0]
        dlines = {norm_line(ln) for ln in dbody.split("\n") if len(norm_line(ln)) >= 16}
        shared = len(qlines & dlines)
        same_name = d.name in qnames and d.path != path
        score = max(rs, 0.8 * ss if ss >= 0.35 else 0.0) + min(0.3, 0.1 * shared) + (0.3 if same_name else 0.0)
        if score < 0.25:
            continue
        why = []
        if same_name:
            why.append("same name")
        if shared:
            why.append(f"{shared} identical line(s)")
        if rs >= 0.25:
            why.append("shared code")
        elif ss >= 0.25:
            why.append("same token shape with different names")
        out.append((score, d, ", ".join(why) or "similar"))
    out.sort(key=lambda x: -x[0])
    return out


def _dup_refs(tree: Tree, path: str, picked: list[tuple[float, Decl, str]]) -> list[dict]:
    refs = []
    for _, d, why in picked:
        where = "this file" if d.path == path else d.path
        refs.append(make_ref(tree, d.path, d.head, d.end, d.name,
                             f"`{d.name}` in {where}: {why}.", max_lines=25))
    return budget(refs)


def gen_dup_in_diff(it: dict) -> list[dict]:
    tree, path, span, decls, inside = excerpt_context(it)
    if not span:
        return []
    qcode = it["excerpt"]
    same = similar_decls(tree, path, inside, qcode, cross=False, same=True, exclude=span)
    cross = similar_decls(tree, path, inside, qcode, cross=True, same=False, exclude=span)
    picked = same[:MAX_REFS - 1]
    if cross and (len(picked) < MAX_REFS - 1 or cross[0][0] >= 0.8):
        picked.append(cross[0])
    picked += [s for s in same[MAX_REFS - 1:] if len(picked) < MAX_REFS]
    return _dup_refs(tree, path, picked[:MAX_REFS])


def gen_dup_cross_file(it: dict) -> list[dict]:
    tree, path, span, decls, inside = excerpt_context(it)
    if not span:
        return []
    cross = similar_decls(tree, path, inside, it["excerpt"], cross=True, same=False, exclude=span)
    return _dup_refs(tree, path, cross[:MAX_REFS])


