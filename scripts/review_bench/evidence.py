PATH_RE = re.compile(r"(?<![\w/.*-])((?:[\w.-]+/)*[\w.-]+\.(?:mdk|sh|mjs|js|c|h|md|toml|json|py|txt|golden|ll))\b")
DIR_RE = re.compile(r"(?<![\w/.-])((?:compiler|stdlib|test|runtime|docs|scripts|playground|pds|archive|sqlite|gzip)/[\w./-]*[\w/])")
ENV_RE = re.compile(r"\b([A-Z][A-Z0-9]*_[A-Z0-9_]*[A-Z0-9])\b")
FLAG_RE = re.compile(r"(?<![\w-])(--[a-z][a-z0-9-]+)")
IDENT_RE = re.compile(r"(?<![\w'])([a-z][a-z0-9]*[A-Z][A-Za-z0-9_']*|[A-Z][a-z0-9]+[A-Z][A-Za-z0-9]*)(?![\w'])")
QUAL_RE = re.compile(r"(?<![\w.])([a-z_][a-z0-9_]*)\.([a-z][A-Za-z0-9_']*)\b")
ISSUE_RE = re.compile(r"(?<![\w&])#(\d{2,5})\b")
TICK_RE = re.compile(r"`([^`\n]+)`")
FILE_EXTS = {"mdk", "sh", "mjs", "js", "c", "h", "md", "toml", "json", "py", "txt", "golden", "ll", "wat"}


def comment_text(excerpt: str, lang: str) -> str:
    out = []
    depth = 0
    for ln in excerpt.split("\n"):
        s = ln.strip()
        if lang == "mdk":
            if depth or s.startswith("{-"):
                depth = max(0, depth + ln.count("{-") - ln.count("-}"))
                out.append(s)
                continue
            if s.startswith("--"):
                out.append(s)
            elif " -- " in ln:
                out.append(ln.split(" -- ", 1)[1])
        else:
            if s.startswith(comment_prefix(lang)):
                out.append(s)
            elif lang in ("sh", "make") and " # " in ln:
                out.append(ln.split(" # ", 1)[1])
            elif lang in ("js", "c") and " // " in ln:
                out.append(ln.split(" // ", 1)[1])
    return "\n".join(out)


def mentions(ctext: str) -> dict[str, list[str]]:
    m: dict[str, list[str]] = {"path": [], "env": [], "flag": [], "ident": [], "qual": [], "issue": []}

    def add(kind, v):
        if v not in m[kind]:
            m[kind].append(v)
    for span in TICK_RE.findall(ctext):
        s = span.strip()
        if PATH_RE.fullmatch(s) or DIR_RE.fullmatch(s):
            add("path", s)
        elif FLAG_RE.fullmatch(s):
            add("flag", s)
        elif re.fullmatch(r"[a-z_][A-Za-z0-9_']*", s) and len(s) >= 3:
            add("ident", s)
        elif re.fullmatch(r"[A-Z][A-Za-z0-9_']*", s) and not ENV_RE.fullmatch(s) and len(s) >= 3:
            add("ident", s)
        elif ENV_RE.fullmatch(s):
            add("env", s)
        else:
            q = QUAL_RE.fullmatch(s)
            if q:
                add("qual", s)
    for x in PATH_RE.findall(ctext) + DIR_RE.findall(ctext):
        add("path", x.rstrip("."))
    for x in ENV_RE.findall(ctext):
        add("env", x)
    for x in FLAG_RE.findall(ctext):
        add("flag", x)
    for x in IDENT_RE.findall(ctext):
        add("ident", x)
    for a, b in QUAL_RE.findall(ctext):
        if (a not in ("e", "i", "etc", "vs") and b not in FILE_EXTS
                and not any(p.endswith(f"{a}.{b}") for p in m["path"])):
            add("qual", f"{a}.{b}")
    for x in ISSUE_RE.findall(ctext):
        add("issue", "#" + x)
    # drop path fragments that are part of a longer path
    m["path"] = [p for p in m["path"] if not any(p != q and q.endswith("/" + p) for q in m["path"])]
    return m


def resolve_path(tree: Tree, p: str, here: str) -> str | None:
    files = tree.files()
    base = str(Path(here).parent)
    for c in (p, f"{base}/{p}", f"compiler/{p}", p.lstrip("./")):
        c = c.rstrip("/")
        if c in files:
            return c
        if any(f.startswith(c + "/") for f in files):
            return c + "/"
    tails = [f for f in files if f.endswith("/" + p)]
    return tails[0] if tails else None


DEF_PATS = (r"^(export +|public export +)?(extern +|data +|type +|interface +)?{n}\b",
            r"^\s*(\| *|= *){n}\b",
            r"^(export +)?(async +)?function\*? +{n}\b",
            r"^(export +)?(const|let|var) +{n}\b",
            r"^{n} *\(\)")


def find_defs(tree: Tree, names: list[str]) -> dict[str, list[tuple[str, int, str]]]:
    if not names:
        return {}
    alt = "(" + "|".join(re.escape(n) for n in names) + ")"
    p = [x.format(n=alt) for x in DEF_PATS]
    hits = (tree.grep(p[:2], ("-E",), ("*.mdk",)) + tree.grep(p[2:4], ("-E",), ("*.mjs", "*.js"))
            + tree.grep(p[4:], ("-E",), ("*.sh",)))
    out: dict[str, list] = {n: [] for n in names}
    per_name = {n: [re.compile(x.format(n=re.escape(n))) for x in DEF_PATS] for n in names}
    for p, ln, t in hits:
        for n in names:
            # the line must define `n` itself, not merely mention it
            if any(rx.search(t) for rx in per_name[n]):
                out[n].append((p, ln, t))
    return out


def gen_comment_stale(it: dict) -> list[dict]:
    tree, path, span, decls, inside = excerpt_context(it)
    lang = lang_of(path)
    ctext = comment_text(it["excerpt"], lang)
    if not ctext.strip():
        return []
    m = mentions(ctext)
    code_in_excerpt = strip_comments(it["excerpt"], lang)
    status: list[tuple[int, str]] = []

    def say(prio: int, text: str) -> None:
        status.append((prio, text))
    strong: list[tuple[int, dict]] = []   # (priority, ref)

    for p in m["path"][:8]:
        r = resolve_path(tree, p, path)
        say(3 if r else 0, f"path `{p}`: " + (f"exists ({r})" if r else "does not exist at this commit"))

    quals = []
    for q in m["qual"][:6]:
        mod, nm = q.split(".", 1)
        files = [f for f in tree.files() if f.endswith(f"/{mod}.mdk") or f == f"{mod}.mdk"]
        if not files:
            continue
        quals.append((q, mod, nm, files))

    idents = [i for i in m["ident"] if i not in ("e.g",)][:14]
    idents += [nm for _, _, nm, _ in quals if nm not in idents]
    defs = find_defs(tree, idents)
    for q, mod, nm, files in quals:
        here = [d for d in defs.get(nm, []) if d[0] in files]
        say(2 if here else 0, f"`{q}`: " + (f"defined in {here[0][0]}:{here[0][1]}" if here
                                    else f"no definition of `{nm}` in {', '.join(files[:2])}"))
    undefined = [i for i in idents if not defs.get(i)]
    counts = {}
    if undefined:
        hits = tree.grep(undefined, ("-w",), ("*.mdk", "*.mjs", "*.js", "*.sh", "*.c", "*.md", "Makefile"))
        for i in undefined:
            ext = [h for h in hits if word_count(h[2], i) and not (h[0] == path and span and span[0] <= h[1] <= span[1])]
            counts[i] = ext
    for i in idents:
        if i in [nm for _, _, nm, _ in quals] and i not in m["ident"]:
            continue
        ds = defs.get(i) or []
        if ds:
            own = [d for d in ds if d[0] == path and span and span[0] <= d[1] <= span[1]]
            if own and len(own) == len(ds):
                say(5, f"`{i}`: defined in the excerpt")
                continue
            here_dir = str(Path(path).parent)
            if not path.startswith("test/"):
                # test/ holds fixture corpora whose top-level names shadow real ones
                ds = [d for d in ds if not d[0].startswith("test/")] or ds
            ds = sorted((d for d in ds if d not in own),
                        key=lambda d: (d[0] != path, str(Path(d[0]).parent) != here_dir, d[0], d[1]))
            files = sorted({d[0] for d in ds})
            if len(files) > 4:
                say(5, f"`{i}`: defined in {len(files)} files")
                continue
            d = ds[0]
            say(2, f"`{i}`: defined at {d[0]}:{d[1]}" + (f" (+{len(ds) - 1} more)" if len(ds) > 1 else ""))
            if word_count(code_in_excerpt, i) == 0:
                strong.append((2, ("def", i, d)))
        else:
            ext = counts.get(i, [])
            if not ext:
                say(0, f"`{i}`: does not occur anywhere else in the tree")
            else:
                fs = sorted({h[0] for h in ext})
                say(1 if len(fs) <= 5 else 6, f"`{i}`: no definition found; mentioned in {_short(fs, 2)}")

    for kind in ("env", "flag"):
        vals = m[kind][:6]
        if not vals:
            continue
        hits = tree.grep(vals, ("-F",), ("*.mdk", "*.sh", "*.mjs", "*.js", "*.c", "*.py", "Makefile", "*.toml"))
        for v in vals:
            ext = [h for h in hits if v in h[2] and not (h[0] == path and span and span[0] <= h[1] <= span[1])
                   and not h[2].lstrip().startswith(("--", "#", "//"))]
            if not ext:
                say(0, f"`{v}`: not read or set in code anywhere in the tree")
            else:
                fs = sorted({h[0] for h in ext})
                say(4, f"`{v}`: appears in code in {len(fs)} file(s), e.g. {_short(fs, 2)}")
                # The production read of an environment variable says what it controls.
                prod = [h for h in ext if h[0].endswith(".mdk") and not h[0].endswith("_test.mdk")
                        and h[0].startswith(("compiler/", "stdlib/")) and f'"{v}' in h[2]]
                if kind == "env" and prod:
                    strong.append((3, ("site", v, prod[0])))
                elif len(fs) <= 3:
                    strong.append((4, ("site", v, ext[0])))
    for iss in m["issue"][:6]:
        say(6, f"{iss}: an issue number (its state is not checked)")

    # Who uses what the comment documents: a comment's claims about callers,
    # consumers or scope are checked against these sites.
    usage = None
    documented = [d for d in inside if d.kind in ("sig", "fn", "data", "extern", "type")
                  and span and span[0] <= d.head <= span[1]][:3]
    if documented:
        names = list(dict.fromkeys(d.name for d in documented))
        hits = tree.grep(names, ("-w",), ("*.mdk", "*.sh", "*.mjs", "*.js", "*.c", "Makefile"))
        own = {(d.path, i) for d in documented for i in range(d.start, d.end + 1)}
        sites = [h for h in hits if (h[0], h[1]) not in own
                 and not h[2].lstrip().startswith(("--", "#", "//"))]
        for nm in names:
            s = [h for h in sites if word_count(h[2], nm)]
            fs = sorted({h[0] for h in s})
            say(1, f"`{nm}` (declared under the comment): " + (
                f"used {len(s)} time(s) outside its definition, in {_short(fs, 3)}" if s
                else "no use anywhere outside its definition"))
        if sites:
            body = "\n".join(f"{p}:{n}: {t.strip()[:140]}" for p, n, t in sites[:12])
            usage = {"file": path, "anchor": "uses of " + ", ".join(names), "sha": tree.sha, "lines": "",
                     "excerpt": body, "note": GEN_NOTE, "fact": "Use sites of the declaration(s) under the comment."}

    refs = [fact_ref(tree, path, "names in the comment", " ".join(t + "." for _, t in sorted(status, key=lambda x: x[0])[:MAX_STATUS]))] if status else []
    if usage:
        refs.append(usage)
    seen = set()
    for _, (kind, name, hit) in sorted(strong, key=lambda x: x[0]):
        p, ln, _ = hit
        if (p, ln) in seen:
            continue
        seen.add((p, ln))
        ds = tree.decls(p)
        d = next((d for d in ds if d.head <= ln <= d.end), None)
        if kind == "def" and d:
            refs.append(make_ref(tree, p, d.head, d.end, d.name,
                                 f"Current definition of `{name}`.", max_lines=20))
        else:
            refs.append(make_ref(tree, p, max(1, ln - 3), ln + 6, d.name if d else name,
                                 f"Where `{name}` is used.", max_lines=10))
        if len(refs) >= MAX_REFS:
            break
    # The code the comment describes, when the excerpt stops before it ends.
    if span and len(refs) < MAX_REFS:
        tail = [d for d in inside if d.end > span[1] and d.kind not in ("import", "other")]
        if tail:
            d = tail[0]
            refs.append(make_ref(tree, path, span[1] + 1, d.end, d.name,
                                 f"The rest of `{d.name}` after the excerpt.", max_lines=30))
    return budget(refs)


